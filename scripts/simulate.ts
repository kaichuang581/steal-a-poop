/**
 * Headless balance simulation. Every seat (including seat 0) is played by the engine's bot logic.
 * Run: npx vite-node scripts/simulate.ts [gamesPerConfig] [--turns=N --from-seats=M]
 *
 * The defaults are the shipped rules. `--turns=3 --from-seats=8` copies the shorter-table
 * experiment from docs/BALANCE_FINDINGS.md, so a proposed rule change can be measured.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import {
  advance, createDictionary, createGame, rankPlayers, MAX_PLAYERS, TURNS_BY_SEATS_OVERRIDES,
  TURNS_PER_PLAYER_PER_ROUND,
} from '../src/engine';
import type { Difficulty, GameState } from '../src/engine';

const dict = createDictionary(readFileSync('public/words.txt', 'utf8').split('\n'));
const ctx = { dict };
const arg = (name: string) => process.argv.find((a) => a.startsWith(`--${name}=`))?.split('=')[1];
// Only bare numbers count as the game count, so a flag in that position cannot become NaN.
const GAMES = Number(process.argv.slice(2).find((a) => /^\d+$/.test(a)) ?? 40);
const TURNS = Number(arg('turns') ?? TURNS_PER_PLAYER_PER_ROUND);
const FROM_SEATS = Number(arg('from-seats') ?? 8);
if (TURNS !== TURNS_PER_PLAYER_PER_ROUND) {
  for (let n = FROM_SEATS; n <= MAX_PLAYERS; n++) TURNS_BY_SEATS_OVERRIDES[n] = TURNS;
}
const CONFIG = TURNS === TURNS_PER_PLAYER_PER_ROUND
  ? `${TURNS_PER_PLAYER_PER_ROUND} turns per player per round at every table size (default)`
  : `${TURNS} turns per player per round at ${FROM_SEATS}+ seats; ${TURNS_PER_PLAYER_PER_ROUND} below that`;
const SEATS = [4, 6, 8, 10];
const DIFFS: Difficulty[] = ['easy', 'medium', 'hard'];

interface Counts { fails: number; timeouts: number; banks: number; bankSum: number; stealPts: number }

/** Steps the clock so every event is seen (the engine keeps only the last 40). */
function play(seed: string, n: number, difficulty: Difficulty, counts: Counts): GameState {
  let s = createGame({ seed, now: 0, humanName: 'bot0', playerCount: n, difficulty }, dict);
  s.players[0].isHuman = false; // seat 0 plays by the same bot rules as everyone else
  s.players[0].difficulty = difficulty;
  s.players[0].personality = 'random';
  s.players[0].bankThreshold = 30;
  let last = 0;
  for (let t = 0; s.phase !== 'gameOver' && t < 3_000_000; t += 250) {
    s = advance(s, ctx, t);
    for (const e of s.events) {
      if (e.id <= last) continue;
      last = e.id;
      if (e.kind === 'stealFail') counts.fails++;
      else if (e.kind === 'timeout') counts.timeouts++;
      else if (e.kind === 'bank') { counts.banks++; counts.bankSum += e.amount; }
    }
  }
  return s;
}

interface Row {
  n: number; difficulty: Difficulty; games: number; ms: number;
  winBySeat: number[]; stealsPerGame: number; failedStealsPerGame: number; timeoutsPerGame: number;
  avgBank: number; avgWinner: number; avgLast: number; negativeEnds: number; minutes: number;
}

const rows: Row[] = [];
for (const n of SEATS) {
  for (const difficulty of DIFFS) {
    const t0 = Date.now();
    const winBySeat = Array<number>(n).fill(0);
    let steals = 0, winSum = 0, lastSum = 0, negative = 0, endMs = 0;
    const counts: Counts = { fails: 0, timeouts: 0, banks: 0, bankSum: 0, stealPts: 0 };
    for (let g = 0; g < GAMES; g++) {
      const s = play(`sim:${n}:${difficulty}:${g}`, n, difficulty, counts);
      const ranked = rankPlayers(s.players);
      for (const w of s.winners ?? []) winBySeat[w] += 1 / (s.winners!.length);
      winSum += ranked[0].banked; lastSum += ranked[n - 1].banked;
      negative += s.players.filter((p) => p.banked < 0).length;
      steals += s.players.reduce((a, p) => a + p.steals, 0);
      endMs += s.events.at(-1)?.at ?? 0;
    }
    rows.push({
      n, difficulty, games: GAMES, ms: Date.now() - t0, winBySeat,
      stealsPerGame: steals / GAMES, failedStealsPerGame: counts.fails / GAMES, timeoutsPerGame: counts.timeouts / GAMES,
      avgBank: counts.banks ? counts.bankSum / counts.banks : 0, avgWinner: winSum / GAMES, avgLast: lastSum / GAMES,
      negativeEnds: negative / GAMES, minutes: endMs / GAMES / 60000,
    });
    console.log(`n=${n} ${difficulty}: ${GAMES} games in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
  }
}

const f = (x: number, d = 1) => x.toFixed(d);
let md = `# Balance simulation\n\nGenerated by \`scripts/simulate.ts\`: ${GAMES} games per row, every seat played by the engine's bot logic (seat 0 included, so no human skill is modelled). Seeds are fixed, so the run is repeatable.\n\nTurns: ${CONFIG}.\n\n`;
md += `| Seats | Bots | Steals/game | Failed steals/game | Timeouts/game | Avg bank | Winner score | Last place | Players ending < 0 | Game length (min) | Seat-0 win % |\n|---|---|---|---|---|---|---|---|---|---|---|\n`;
for (const r of rows) {
  md += `| ${r.n} | ${r.difficulty} | ${f(r.stealsPerGame)} | ${f(r.failedStealsPerGame)} | ${f(r.timeoutsPerGame)} | ${f(r.avgBank)} | ${f(r.avgWinner, 0)} | ${f(r.avgLast, 0)} | ${f(r.negativeEnds)} | ${f(r.minutes)} | ${f((r.winBySeat[0] / r.games) * 100, 0)}% |\n`;
}
md += `\n## Win share by seat\n\n`;
for (const r of rows) md += `- **${r.n} seats, ${r.difficulty}:** ${r.winBySeat.map((w, i) => `s${i} ${f((w / r.games) * 100, 0)}%`).join(', ')}\n`;
mkdirSync('docs', { recursive: true });
writeFileSync('docs/BALANCE.md', md);
console.log('wrote docs/BALANCE.md');
