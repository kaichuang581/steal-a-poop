/**
 * The animal report (V5.1 Parts 3 and 9): every number the Part 7 tests compute, for every species, with what fails.
 *   npx vite-node tools/animalReport.ts -- --out docs/skin/animals-v5_1/F0-report.md [--title "F0"]
 */
import { writeFileSync } from 'node:fs';
import { animalModel } from '../src/skin/voxel/animals';
import { chickenOrientation, faceRule, notch, proportions, RATIO_NAMES, ratioFails, roots, SHEET, sheepHead } from '../src/skin/voxel/animals/measure';
import type { Ratio } from '../src/skin/voxel/animals/measure';
import type { Species } from '../src/skin/voxel/animals/rig';

const arg = (n: string, d = '') => { const i = process.argv.indexOf(`--${n}`); return i >= 0 ? process.argv[i + 1] : d; };
const SPECIES: Species[] = ['sheep', 'pig', 'cow', 'horse', 'goat', 'chicken'];
const f = (n: number) => (Number.isFinite(n) ? n.toFixed(2) : '–');
const lines: string[] = [`# Farm animals v5.1: ${arg('title', 'report')}`, '', `Generated by tools/animalReport.ts. Every number the V5.1 Part 7 tests compute; **bold** is outside its range.`, ''];
let failures = 0;
const failed: Record<string, string[]> = {};
const note = (s: Species, what: string) => { (failed[s] ??= []).push(what); failures++; };

lines.push('## Proportions (Part 4.1)', '', `| Ratio | ${SPECIES.join(' | ')} |`, `|---|${SPECIES.map(() => '---').join('|')}|`);
const props = Object.fromEntries(SPECIES.map((s) => [s, proportions(animalModel(s))]));
for (const r of Object.keys(RATIO_NAMES) as Ratio[]) {
  lines.push(`| ${RATIO_NAMES[r]} | ${SPECIES.map((s) => {
    const v = props[s][r], [lo, hi] = SHEET[s][r], bad = v < lo - 1e-9 || v > hi + 1e-9;
    if (bad) note(s, RATIO_NAMES[r]);
    return `${bad ? '**' : ''}${f(v)}${bad ? '**' : ''} (${lo}–${hi > 5 ? '' : hi})`;
  }).join(' | ')} |`);
}
lines.push('', '## The notch test (Part 4.2.5)', '', '| Species | Columns | Deepest dip | Sharpest notch | |', '|---|---|---|---|---|');
for (const s of SPECIES) { const n = notch(animalModel(s)); if (!n.ok) note(s, 'notch'); lines.push(`| ${s} | z ${n.from} to ${n.to} | ${n.dip} | ${n.spike} | ${n.ok ? 'pass' : '**fail**'} |`); }
lines.push('', '## Roots (Part 4.2.4)', '', '| Species | Part | Touching voxels | Span x, y, z | |', '|---|---|---|---|---|');
for (const s of SPECIES) for (const r of roots(animalModel(s))) { if (!r.ok) note(s, `root ${r.part}`); lines.push(`| ${s} | ${r.part} | ${r.contact} | ${r.spans.join(', ')} | ${r.ok ? 'pass' : '**fail**'} |`); }
lines.push('', '## The face rule (Part 4.4)', '', '| Species | Part | Voxels off the face | Below the chin | |', '|---|---|---|---|---|');
for (const s of SPECIES) for (const c of faceRule(animalModel(s))) { if (!c.ok) { note(s, `face ${c.part}`); lines.push(`| ${s} | ${c.part} | ${c.off} | ${c.belowChin} | **fail** |`); } }
lines.push('', '(Parts that pass are not listed.)', '', '## Chicken orientation (Part 5.6) and the sheep head (Part 7.8)', '');
const co = chickenOrientation(animalModel('chicken'));
if (!co.ok) note('chicken', 'orientation');
lines.push(`- Chicken: torso L / H ${f(co.torsoLH)} (≥ 1.6), head ahead of the breast ${co.headAhead}, tail the highest after the comb ${co.tailHighest}: ${co.ok ? 'pass' : '**fail**'}`);
const sh = sheepHead(animalModel('sheep'));
if (!sh.ok) note('sheep', 'head shape');
lines.push(`- Sheep: wider than tall ${sh.wider}, muzzle above the body's centre ${sh.muzzleAbove}, top near the back line ${sh.topNearBack}, ears 4+ long ${sh.earsLong}: ${sh.ok ? 'pass' : '**fail**'}`);
lines.push('', '## Budgets (Part 4.7)', '', '| Species | Voxels (≤ 3,200) | Triangles (≤ 10,000) | Colours (≤ 14) | Parts (≤ 24) |', '|---|---|---|---|---|');
for (const s of SPECIES) { const st = animalModel(s).stats; lines.push(`| ${s} | ${st.voxels} (${3200 - st.voxels} spare) | ${st.triangles} | ${st.colours} | ${st.parts} |`); }
lines.push('', '## Summary', '', `${failures} checks fail.`, '', ...SPECIES.map((s) => `- ${s}: ${failed[s]?.length ? failed[s].join(', ') : 'all pass'}`), '');
const out = arg('out');
if (out) writeFileSync(out, lines.join('\n'));
console.log(lines.join('\n'));
